static UINT8 glyph16[16];


const UINT8 *font8x16_get(UINT8 code)
{
    UINTN y;


    if (code >= 128)
        return blank;


    for (y = 0; y < 8; y++)
    {
        glyph16[y * 2] =
            font8x8[code][y];

        glyph16[y * 2 + 1] =
            font8x8[code][y];
    }


    return glyph16;
}

